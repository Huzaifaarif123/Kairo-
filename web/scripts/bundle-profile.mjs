// Bundles the main candidate profile into the build as a fallback, so the live
// site still has it even if the hosting platform doesn't copy repo files
// next to the server functions. Runs automatically before `dev` and `build`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const web = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(web, '..', '.claude', 'skills', 'job-application-assistant', '01-candidate-profile.md');
const target = path.join(web, 'lib', 'generated', 'main-profile.ts');

const markdown = fs.existsSync(source) ? fs.readFileSync(source, 'utf-8') : '';
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, `// Generated by scripts/bundle-profile.mjs - do not edit\nexport const MAIN_PROFILE_MARKDOWN = ${JSON.stringify(markdown)};\n`);
console.log(markdown ? `Bundled main profile (${markdown.length} chars)` : 'Main profile not found; bundled an empty fallback');
